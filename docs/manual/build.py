# Builds manual.html (BIM Tasks user manual) from the demo screenshots. Run: python build.py <shots dir> <fonts dir> <logo>
import sys, html, pathlib
from PIL import Image

SHOTS, FONTS, LOGO = map(pathlib.Path, sys.argv[1:4])
OUT = pathlib.Path(__file__).parent
IMG = OUT / 'img'; IMG.mkdir(exist_ok=True)


def shot(name, cap=''):
    src = SHOTS / f'{name}.png'
    dst = IMG / f'{name}.jpg'
    if not dst.exists():
        Image.open(src).convert('RGB').save(dst, quality=82, optimize=True)
    return f'<figure><img src="img/{name}.jpg">{f"<figcaption>{cap}</figcaption>" if cap else ""}</figure>'


def ul(*items):
    return '<ul>' + ''.join(f'<li>{i}</li>' for i in items) + '</ul>'


def tip(t, kind='tip'):
    label = {'tip': '💡 نصيحة', 'warn': '⚠️ انتبه', 'note': 'ℹ️ معلومة'}[kind]
    return f'<div class="box {kind}"><b>{label}:</b> {t}</div>'


def table(head, rows):
    return ('<table><thead><tr>' + ''.join(f'<th>{h}</th>' for h in head) + '</tr></thead><tbody>' +
            ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows) + '</tbody></table>')


def tg(lines, buttons):
    """A Telegram-like message with inline buttons (texts taken from the real bot code)."""
    body = '<br>'.join(html.escape(l) if l else '&nbsp;' for l in lines)
    kb = ''.join('<div class="kbrow">' + ''.join(f'<span>{html.escape(b)}</span>' for b in row) + '</div>' for row in buttons)
    return f'<div class="tg"><div class="bubble">{body}</div><div class="kb">{kb}</div></div>'


chapters = []  # (id, title, html)


def ch(title, *parts):
    chapters.append((f'c{len(chapters)+1}', title, ''.join(parts)))


def sec(title, *parts):
    return f'<h3>{title}</h3>' + ''.join(parts)


